/* Транслитерация към чиста латиница (ASCII) за имена на файлове. Покрива писмеността на 15-те
 * поддържани езика: латиница с диакритика (de/it/es/fr/pt/en — през NFKD), кирилица (bg/ru/uk/ky),
 * арабица (ar), гръцки (бонус) и арабско-индийски/деванагари цифри. Йероглифите (zh-Hant/ja) и
 * деванагари букви (hi) нямат еднозначна латинизация без речник → отпадат (името се подсигурява
 * с пореден номер + дата в извикващия код). */
'use strict';

const CYR = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l',
  м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch',
  ш: 'sh', щ: 'sht', ъ: 'a', ь: '', ю: 'yu', я: 'ya',
  ё: 'yo', э: 'e', ы: 'y', і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u', ң: 'ng', ү: 'u', ө: 'o', һ: 'h', ҷ: 'j',
};
const AR = {
  'ا': 'a', 'أ': 'a', 'إ': 'i', 'آ': 'a', 'ب': 'b', 'ت': 't', 'ث': 'th', 'ج': 'j', 'ح': 'h', 'خ': 'kh',
  'د': 'd', 'ذ': 'dh', 'ر': 'r', 'ز': 'z', 'س': 's', 'ش': 'sh', 'ص': 's', 'ض': 'd', 'ط': 't', 'ظ': 'z',
  'ع': 'a', 'غ': 'gh', 'ف': 'f', 'ق': 'q', 'ك': 'k', 'ل': 'l', 'م': 'm', 'ن': 'n', 'ه': 'h', 'و': 'w',
  'ي': 'y', 'ى': 'a', 'ة': 'h', 'ء': '', 'ئ': 'y', 'ؤ': 'w',
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
};
const GR = {
  α: 'a', β: 'v', γ: 'g', δ: 'd', ε: 'e', ζ: 'z', η: 'i', θ: 'th', ι: 'i', κ: 'k', λ: 'l', μ: 'm',
  ν: 'n', ξ: 'x', ο: 'o', π: 'p', ρ: 'r', σ: 's', ς: 's', τ: 't', υ: 'y', φ: 'f', χ: 'ch', ψ: 'ps', ω: 'o',
};
const DEV_DIGITS = { '०': '0', '१': '1', '२': '2', '३': '3', '४': '4', '५': '5', '६': '6', '७': '7', '८': '8', '९': '9' };

// пълна карта (малки + главни букви)
const MAP = {};
for (const src of [CYR, GR]) for (const k in src) { MAP[k] = src[k]; MAP[k.toUpperCase()] = src[k] ? (src[k][0].toUpperCase() + src[k].slice(1)) : ''; }
for (const k in AR) MAP[k] = AR[k];
for (const k in DEV_DIGITS) MAP[k] = DEV_DIGITS[k];

function transliterate(s) {
  s = String(s == null ? '' : s);
  let out = '';
  for (const ch of s) out += (ch in MAP) ? MAP[ch] : ch;
  // диакритика на латиницата (ü→u, ñ→n, ç→c, é→e …) през декомпозиция
  return out.normalize('NFKD').replace(/[̀-ͯ]/g, '');
}

module.exports = { transliterate };
